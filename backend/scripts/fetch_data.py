"""Download the offline data the backend needs.

Usage (from backend/):
    python scripts/fetch_data.py kernels   # NAIF SPICE kernels -> data/kernels/
    python scripts/fetch_data.py dems      # LOLA DEMs -> data/dem/ (raw in data/raw/)
"""

import argparse
import shutil
import sys
import urllib.request
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BACKEND_DIR / "data"
KERNELS_DIR = DATA_DIR / "kernels"
RAW_DIR = DATA_DIR / "raw"
DEM_DIR = DATA_DIR / "dem"

NAIF_BASE_URL = "https://naif.jpl.nasa.gov/pub/naif/generic_kernels/"

# (file name, subpath under NAIF_BASE_URL), per doc/tech-stack.md > Ephemeris
KERNELS = [
    ("de440s.bsp", "spk/planets/"),
    ("moon_pa_de440_200625.bpc", "pck/"),
    ("moon_de440_250416.tf", "fk/satellites/"),
    ("naif0012.tls", "lsk/"),
    ("pck00011.tpc", "pck/"),
]


def download(url: str, dest: Path) -> None:
    """Download url to dest via a .part file, renamed only once complete."""
    part = dest.with_name(dest.name + ".part")
    try:
        with urllib.request.urlopen(url, timeout=60) as resp, open(part, "wb") as out:
            shutil.copyfileobj(resp, out)
        part.replace(dest)
    finally:
        part.unlink(missing_ok=True)


def fetch_kernels(args: argparse.Namespace) -> None:
    """Download the SPICE kernels into KERNELS_DIR, skipping existing files."""
    KERNELS_DIR.mkdir(parents=True, exist_ok=True)
    for name, subpath in KERNELS:
        dest = KERNELS_DIR / name
        if dest.exists():
            print(f"skip      {name} (already present)")
            continue
        url = NAIF_BASE_URL + subpath + name
        print(f"download  {name} <- {url}")
        download(url, dest)
    write_metakernel()


def _spice_string_pieces(s: str, width: int = 70) -> list[str]:
    """Split s into kernel-pool string pieces joined with SPICE's '+' marker.

    Kernel-pool strings are limited to 80 chars; a piece ending in '+' is
    continued by the next one.
    """
    chunks = [s[i:i + width] for i in range(0, len(s), width)]
    return [c + "+" for c in chunks[:-1]] + chunks[-1:]


def write_metakernel() -> None:
    """Write KERNELS_DIR/meta.tm with an absolute $KERNELS path.

    SPICE resolves relative paths against the process cwd, not the
    metakernel's folder, so the absolute path is baked in at fetch time.
    Only rewrites the file if its contents would change.
    """
    path_lines = "\n".join(
        f"                     '{p}'" for p in _spice_string_pieces(str(KERNELS_DIR))
    )
    kernel_lines = "\n".join(f"                     '$KERNELS/{name}'" for name, _ in KERNELS)
    text = f"""KPL/MK

Metakernel for the lunar landing site backend.
Generated by backend/scripts/fetch_data.py - do not edit by hand.

\\begindata

   PATH_VALUES     = (
{path_lines}
                     )

   PATH_SYMBOLS    = ( 'KERNELS' )

   KERNELS_TO_LOAD = (
{kernel_lines}
                     )

\\begintext
"""
    meta = KERNELS_DIR / "meta.tm"
    if meta.exists() and meta.read_text() == text:
        print("skip      meta.tm (up to date)")
        return
    meta.write_text(text)
    print(f"write     meta.tm -> {meta}")


# --- LOLA DEMs (ticket 1.3) -------------------------------------------------

LOLA_GDR_URL = (
    "https://pds-geosciences.wustl.edu/lro/lro-l-lola-3-rdr-v1/lrolol_1xxx/data/lola_gdr/"
)

# Both products are 16-bit integers: height_m = DN * 0.5, relative to a
# 1737.4 km sphere. The GeoTIFFs keep the raw DN and carry scale=0.5, so
# readers must apply it: `ds.read(1) * ds.scales[0]` -> metres.
DEM_SCALE_M = 0.5

# Preset south pole sites (lat, lon deg), from frontend/src/sites.ts until
# GET /sites (ticket 3.5) owns the list. The polar crop covers all of them.
POLAR_CROP_SITES = [
    (-89.67, 129.78),  # Shackleton crater (Artemis III)
    (-89.45, 222.7),   # Connecting Ridge (Artemis III)
    (-86.0, 2.9),      # Malapert Massif (Artemis III)
]
# Kept around the sites' bounding box at 20 m. Terrain beyond this comes
# from the global LDEM_64 (far horizon).
POLAR_CROP_MARGIN_M = 30_000

# (product stem as named in the PDS label, subdirectory, output GeoTIFF)
DEMS = {
    "polar": ("LDEM_85S_20M", "polar/img/", "ldem_85s_20m_crop.tif"),
    "global": ("LDEM_64", "cylindrical/img/", "ldem_64.tif"),
}

GTIFF_PROFILE = {
    "driver": "GTiff",
    "dtype": "int16",
    "compress": "deflate",
    "predictor": 2,
    "zlevel": 9,
    "tiled": True,
    "blockxsize": 512,
    "blockysize": 512,
}


def fetch_dems(args: argparse.Namespace) -> None:
    """Download both LOLA DEMs + labels and write compressed GeoTIFFs to DEM_DIR."""
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    DEM_DIR.mkdir(parents=True, exist_ok=True)
    for kind, (stem, subdir, out_name) in DEMS.items():
        out = DEM_DIR / out_name
        if out.exists():
            print(f"skip      {out_name} (already present)")
            continue
        # Keep the label's own upper-case file names so GDAL can find the
        # .IMG that the detached .LBL points to.
        for ext in ("LBL", "IMG"):
            dest = RAW_DIR / f"{stem}.{ext}"
            if dest.exists():
                print(f"skip      {dest.name} (already downloaded)")
                continue
            url = LOLA_GDR_URL + subdir + f"{stem}.{ext}".lower()
            print(f"download  {dest.name} <- {url}")
            download(url, dest)
        label = RAW_DIR / f"{stem}.LBL"
        if kind == "polar":
            write_polar_crop(label, out)
        else:
            write_full_geotiff(label, out)


def _write_geotiff(src, out: Path, window) -> None:
    """Copy `window` of src to a tiled, compressed int16 GeoTIFF at out.

    Written to a .part file and renamed when complete, like download().
    """
    import rasterio
    from rasterio.windows import Window

    profile = dict(
        GTIFF_PROFILE,
        width=int(window.width),
        height=int(window.height),
        count=1,
        crs=src.crs,
        transform=src.window_transform(window),
    )
    part = out.with_name(out.name + ".part")
    try:
        with rasterio.open(part, "w", **profile) as dst:
            dst.scales = (DEM_SCALE_M,)
            dst.offsets = (0.0,)
            dst.units = ("m",)
            dst.update_tags(
                HEIGHT_REFERENCE="metres above a 1737.4 km sphere after applying scale",
                SOURCE=f"LOLA {src.name}",
            )
            # Copy in strips of tile rows to keep memory low.
            step = GTIFF_PROFILE["blockysize"] * 4
            for row in range(0, int(window.height), step):
                h = min(step, int(window.height) - row)
                data = src.read(
                    1, window=Window(window.col_off, window.row_off + row, window.width, h)
                )
                dst.write(data, 1, window=Window(0, row, window.width, h))
        part.replace(out)
    finally:
        part.unlink(missing_ok=True)
    size_mb = out.stat().st_size / 1e6
    print(f"write     {out.name} ({int(window.width)}x{int(window.height)}, {size_mb:.0f} MB)")


def write_polar_crop(label: Path, out: Path) -> None:
    """Crop LDEM_85S_20M to the preset south pole sites plus a margin."""
    import rasterio
    from rasterio.crs import CRS
    from rasterio.warp import transform
    from rasterio.windows import Window, from_bounds

    with rasterio.open(label) as src:
        moon_lonlat = CRS.from_proj4("+proj=longlat +R=1737400 +no_defs")
        lats = [lat for lat, _ in POLAR_CROP_SITES]
        lons = [lon for _, lon in POLAR_CROP_SITES]
        xs, ys = transform(moon_lonlat, src.crs, lons, lats)
        m = POLAR_CROP_MARGIN_M
        window = from_bounds(
            min(xs) - m, min(ys) - m, max(xs) + m, max(ys) + m, transform=src.transform
        )
        # Snap to whole pixels and clip to the raster.
        window = window.round_offsets().round_lengths()
        window = window.intersection(Window(0, 0, src.width, src.height))
        _write_geotiff(src, out, window)


def write_full_geotiff(label: Path, out: Path) -> None:
    """Convert the whole of a PDS DEM (LDEM_64) to a compressed GeoTIFF."""
    import rasterio
    from rasterio.windows import Window

    with rasterio.open(label) as src:
        _write_geotiff(src, out, Window(0, 0, src.width, src.height))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="fetch_data.py",
        description="Download the offline data the backend needs.",
    )
    sub = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")

    p_kernels = sub.add_parser("kernels", help="download NAIF SPICE kernels")
    p_kernels.set_defaults(func=fetch_kernels)

    p_dems = sub.add_parser("dems", help="download LOLA DEMs and write cropped GeoTIFFs")
    p_dems.set_defaults(func=fetch_dems)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
