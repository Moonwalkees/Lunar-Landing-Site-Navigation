"""Download the offline data the backend needs.

Usage (from backend/):
    python scripts/fetch_data.py kernels   # NAIF SPICE kernels -> data/kernels/
    python scripts/fetch_data.py dems      # LOLA elevation maps  -> data/dem/
"""

import argparse
import math
import re
import shutil
import sys
import urllib.request
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BACKEND_DIR / "data"
KERNELS_DIR = DATA_DIR / "kernels"

DEM_DIR = DATA_DIR / "dem"

NAIF_BASE_URL = "https://naif.jpl.nasa.gov/pub/naif/generic_kernels/"
LOLA_BASE_URL = (
    "https://pds-geosciences.wustl.edu/lro/lro-l-lola-3-rdr-v1/lrolol_1xxx/data/lola_gdr/"
)

# (file stem, subpath under LOLA_BASE_URL), per doc/tech-stack.md > Terrain
POLAR_DEM = ("ldem_85s_20m", "polar/img/")
GLOBAL_DEM = ("ldem_64", "cylindrical/img/")
POLAR_OUT = "ldem_85s_20m_crop.tif"
GLOBAL_OUT = "ldem_64.tif"

MOON_RADIUS_M = 1737400.0
# How much ground to keep around the preset south pole sites when cropping the polar map.
CROP_MARGIN_M = 45_000.0

# (file name, subpath under NAIF_BASE_URL), per doc/tech-stack.md > Ephemeris
KERNELS = [
    ("de440s.bsp", "spk/planets/"),
    ("moon_pa_de440_200625.bpc", "pck/"),
    ("moon_de440_250416.tf", "fk/satellites/"),
    ("naif0012.tls", "lsk/"),
    ("pck00011.tpc", "pck/"),
]


def download(url: str, dest: Path) -> None:
    """Download url to dest via a .part file, renamed only once complete."""
    part = dest.with_name(dest.name + ".part")
    try:
        with urllib.request.urlopen(url, timeout=60) as resp, open(part, "wb") as out:
            shutil.copyfileobj(resp, out)
        part.replace(dest)
    finally:
        part.unlink(missing_ok=True)


def fetch_kernels(args: argparse.Namespace) -> None:
    """Download the SPICE kernels into KERNELS_DIR, skipping existing files."""
    KERNELS_DIR.mkdir(parents=True, exist_ok=True)
    for name, subpath in KERNELS:
        dest = KERNELS_DIR / name
        if dest.exists():
            print(f"skip      {name} (already present)")
            continue
        url = NAIF_BASE_URL + subpath + name
        print(f"download  {name} <- {url}")
        download(url, dest)
    write_metakernel()


def _spice_string_pieces(s: str, width: int = 70) -> list[str]:
    """Split s into kernel-pool string pieces joined with SPICE's '+' marker.

    Kernel-pool strings are limited to 80 chars; a piece ending in '+' is
    continued by the next one.
    """
    chunks = [s[i:i + width] for i in range(0, len(s), width)]
    return [c + "+" for c in chunks[:-1]] + chunks[-1:]


def write_metakernel() -> None:
    """Write KERNELS_DIR/meta.tm with an absolute $KERNELS path.

    SPICE resolves relative paths against the process cwd, not the
    metakernel's folder, so the absolute path is baked in at fetch time.
    Only rewrites the file if its contents would change.
    """
    path_lines = "\n".join(
        f"                     '{p}'" for p in _spice_string_pieces(str(KERNELS_DIR))
    )
    kernel_lines = "\n".join(f"                     '$KERNELS/{name}'" for name, _ in KERNELS)
    text = f"""KPL/MK

Metakernel for the lunar landing site backend.
Generated by backend/scripts/fetch_data.py - do not edit by hand.

\\begindata

   PATH_VALUES     = (
{path_lines}
                     )

   PATH_SYMBOLS    = ( 'KERNELS' )

   KERNELS_TO_LOAD = (
{kernel_lines}
                     )

\\begintext
"""
    meta = KERNELS_DIR / "meta.tm"
    if meta.exists() and meta.read_text() == text:
        print("skip      meta.tm (up to date)")
        return
    meta.write_text(text)
    print(f"write     meta.tm -> {meta}")


def _label_number(label: str, key: str) -> float:
    """Read one numeric field from a PDS label."""
    match = re.search(rf"^\s*{key}\s*=\s*([-+\d.eE]+)", label, re.MULTILINE)
    if not match:
        raise ValueError(f"{key} not found in the PDS label")
    return float(match.group(1))


def _moon_crs(projection: str) -> str:
    """WKT for a map of the Moon as a 1737.4 km sphere."""
    geographic = (
        'GEOGCS["Moon",DATUM["Moon",SPHEROID["Moon",1737400,0]],'
        'PRIMEM["Reference_Meridian",0],UNIT["degree",0.0174532925199433]]'
    )
    if projection == "polar":
        parameters = (
            'PROJECTION["Polar_Stereographic"],PARAMETER["latitude_of_origin",-90],'
            'PARAMETER["central_meridian",0],'
        )
    else:
        parameters = (
            'PROJECTION["Equirectangular"],PARAMETER["standard_parallel_1",0],'
            'PARAMETER["central_meridian",0],'
        )
    return (
        f'PROJCS["Moon {projection}",{geographic},{parameters}'
        'PARAMETER["false_easting",0],PARAMETER["false_northing",0],UNIT["metre",1]]'
    )


def _south_pole_crop(half_width_m: float, pixel_m: float) -> tuple[int, int, int, int]:
    """Pixel window (row0, row1, col0, col1) of the polar map around the preset polar sites."""
    sys.path.insert(0, str(BACKEND_DIR))
    from app.sites import PRESETS

    xs, ys = [], []
    for site in PRESETS:
        lat, lon = float(site["lat"]), math.radians(float(site["lon"]))
        if lat > -85.0:
            continue
        r = 2 * MOON_RADIUS_M * math.tan(math.radians(90 + lat) / 2)
        xs.append(r * math.sin(lon))
        ys.append(r * math.cos(lon))
    if not xs:
        raise ValueError("No preset sites south of 85S to crop the polar map around")

    left = max(min(xs) - CROP_MARGIN_M, -half_width_m)
    right = min(max(xs) + CROP_MARGIN_M, half_width_m)
    bottom = max(min(ys) - CROP_MARGIN_M, -half_width_m)
    top = min(max(ys) + CROP_MARGIN_M, half_width_m)
    col0 = int(math.floor((left + half_width_m) / pixel_m))
    col1 = int(math.ceil((right + half_width_m) / pixel_m))
    row0 = int(math.floor((half_width_m - top) / pixel_m))
    row1 = int(math.ceil((half_width_m - bottom) / pixel_m))
    return row0, row1, col0, col1


def _fetch_raw(stem: str, subpath: str, raw_dir: Path) -> tuple[Path, str]:
    """Download a LOLA .img and its label, skipping files that are already there."""
    for ext in (".lbl", ".img"):
        dest = raw_dir / (stem + ext)
        if dest.exists():
            print(f"skip      {dest.name} (already present)")
            continue
        url = LOLA_BASE_URL + subpath + stem + ext
        print(f"download  {dest.name} <- {url}")
        download(url, dest)
    return raw_dir / (stem + ".img"), (raw_dir / (stem + ".lbl")).read_text(errors="replace")


def fetch_dems(args: argparse.Namespace) -> None:
    """Download the LOLA elevation maps and save them as GeoTIFFs in DEM_DIR.

    Heights stay as 16-bit numbers in half metres above the 1737.4 km sphere; the
    GeoTIFFs record that scale, so ``rasterio`` readers multiply by ``dataset.scales[0]``.
    The polar map is cropped to the area around the preset south pole sites.
    """
    import numpy as np
    import rasterio
    from rasterio.enums import Resampling
    from rasterio.transform import from_origin

    raw_dir = DEM_DIR / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    options = dict(driver="GTiff", count=1, dtype="int16", compress="deflate", predictor=2,
                   tiled=True, blockxsize=512, blockysize=512)

    polar_out = DEM_DIR / POLAR_OUT
    if polar_out.exists():
        print(f"skip      {POLAR_OUT} (already present)")
    else:
        img, label = _fetch_raw(*POLAR_DEM, raw_dir)
        lines, samples = int(_label_number(label, "LINES")), int(_label_number(label, "LINE_SAMPLES"))
        pixel = _label_number(label, "MAP_SCALE")
        half = (_label_number(label, "SAMPLE_PROJECTION_OFFSET") + 0.5) * pixel
        heights = np.memmap(img, dtype="<i2", mode="r", shape=(lines, samples))
        row0, row1, col0, col1 = _south_pole_crop(half, pixel)
        crop = np.ascontiguousarray(heights[row0:row1, col0:col1])
        with rasterio.open(
            polar_out, "w", height=crop.shape[0], width=crop.shape[1], crs=_moon_crs("polar"),
            transform=from_origin(-half + col0 * pixel, half - row0 * pixel, pixel, pixel), **options,
        ) as out:
            out.write(crop, 1)
            out.scales = (_label_number(label, "SCALING_FACTOR"),)
            out.build_overviews([2, 4, 8, 16], Resampling.average)
        print(f"write     {POLAR_OUT} ({crop.shape[1]} x {crop.shape[0]} px at {pixel:g} m)")
        del heights

    global_out = DEM_DIR / GLOBAL_OUT
    if global_out.exists():
        print(f"skip      {GLOBAL_OUT} (already present)")
    else:
        img, label = _fetch_raw(*GLOBAL_DEM, raw_dir)
        lines, samples = int(_label_number(label, "LINES")), int(_label_number(label, "LINE_SAMPLES"))
        pixel = MOON_RADIUS_M * math.radians(1.0 / _label_number(label, "MAP_RESOLUTION"))
        heights = np.memmap(img, dtype="<i2", mode="r", shape=(lines, samples))
        with rasterio.open(
            global_out, "w", height=lines, width=samples, crs=_moon_crs("equirectangular"),
            transform=from_origin(0.0, lines / 2 * pixel, pixel, pixel), **options,
        ) as out:
            out.write(heights, 1)
            out.scales = (_label_number(label, "SCALING_FACTOR"),)
        print(f"write     {GLOBAL_OUT} ({samples} x {lines} px at {pixel:.0f} m)")
        del heights

    if not args.keep_raw:
        shutil.rmtree(raw_dir, ignore_errors=True)
        print("remove    raw downloads (pass --keep-raw to keep them)")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="fetch_data.py",
        description="Download the offline data the backend needs.",
    )
    sub = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")

    p_kernels = sub.add_parser("kernels", help="download NAIF SPICE kernels")
    p_kernels.set_defaults(func=fetch_kernels)

    p_dems = sub.add_parser("dems", help="download and crop LOLA elevation maps")
    p_dems.add_argument("--keep-raw", action="store_true", help="keep the downloaded .img files")
    p_dems.set_defaults(func=fetch_dems)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
